// Labels match the BLS "job outlook" wording for the 2025–35 projections.
export function outlookLabel(growthPct: number): string {
  if (growthPct >= 7) return "Much faster than average";
  if (growthPct >= 5) return "Faster than average";
  if (growthPct >= 3) return "As fast as average";
  if (growthPct >= 1) return "Slower than average";
  if (growthPct === 0) return "Little or no change";
  return "Declining";
}
